#!/usr/bin/env python3
"""Discover reachable Lean modules and generate their constant initializers.

This experimental packager is pinned to Lean 4.34.1's generated C layout. It
uses release bootstrap C only as a symbol index; standard-library modules are
regenerated by the project's actual compiler before cross-compilation. Runtime
constants use their original generated initializers in import/declaration order.
No compiler/tactic registration initializers or unresolved-symbol stubs are used.
"""
from hashlib import sha256
from pathlib import Path
import os
import re
import subprocess

ROOT = Path(__file__).resolve().parents[2]
os.chdir(ROOT)
OUT = ROOT / '.lake/wasm'
PREFIX = Path(subprocess.check_output(['lean', '--print-prefix'], text=True).strip())
SOURCE = OUT / 'toolchains/lean4-4.34.1/src'
BOOTSTRAP = SOURCE.parent / 'stage0/stdlib'
WORK = OUT / 'json-build'
MAKEFILE = ROOT / 'experiments/wasm/Makefile'


def make(*targets, capture=False):
    # Make owns all compiler commands and file dependencies. Discovery needs the
    # linker diagnostics to find the next modules/constants in the closure.
    return subprocess.run(['make', '--no-print-directory', '-f', str(MAKEFILE),
                           '-j4', *map(str, targets)],
                          capture_output=capture, text=True, check=not capture)


def write_changed(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


# Source index includes shared specializations emitted into imported packages.
paths = [*BOOTSTRAP.rglob('*.c'), *(ROOT / '.lake/build/ir/Forms').rglob('*.c'),
         *(ROOT / '.lake/packages').glob('*/.lake/build/ir/**/*.c'), OUT / 'JsonEval.c']
function_pattern = re.compile(r'^LEAN_EXPORT [^\n;{}]*?\b(\w+)\([^;\n]*\)\s*\{', re.MULTILINE)
global_pattern = re.compile(r'^LEAN_EXPORT (?:lean_object\*|u?int(?:8|16|32|64)_t|size_t|double|float) (\w+);', re.MULTILINE)
index = {}
texts = {}


def register(path, text):
    texts[path] = text
    for symbol in [*function_pattern.findall(text), *global_pattern.findall(text)]:
        index[symbol] = path


for path in paths:
    register(path, path.read_text())
selected = {}
constants = {}


def select(path):
    if path in selected:
        return
    if path.is_relative_to(BOOTSTRAP):
        module = path.relative_to(BOOTSTRAP).with_suffix('')
        generated = WORK / 'core' / module.with_suffix('.c')
        generated.parent.mkdir(parents=True, exist_ok=True)
        make(generated.relative_to(ROOT))
        register(path, generated.read_text())
    selected[path] = None
    constants[path] = set()


select(OUT / 'JsonEval.c')


def hook(path):
    return 'json_constants_' + sha256(str(path.relative_to(ROOT)).encode()).hexdigest()[:16]


def module_source(path):
    text = texts[path]
    if constants[path]:
        # Preserve declaration order from the original module initializer.
        init = text
        statements = []
        for line in init.splitlines():
            symbol = line.split(' = ', 1)[0]
            if symbol in constants[path]:
                if not re.fullmatch(r'\w+ = _init_\w+\(\);', line):
                    raise RuntimeError(f'Unsupported initialization: {line}')
                statements.append(line)
                if f'lean_mark_persistent({symbol});' in init:
                    statements.append(f'lean_mark_persistent({symbol});')
        if len([line for line in statements if ' = ' in line]) != len(constants[path]):
            raise RuntimeError(f'Missing constant initializer in {path}')
        text += '\nvoid ' + hook(path) + '(void) {\n' + '\n'.join(statements) + '\n}\n'
    generated = WORK / (sha256(text.encode()).hexdigest() + '.c')
    if not generated.exists():
        generated.write_text(text)
    return generated


def initialize_source():
    ordered = []
    visited = set()

    def visit(path):
        if path in visited:
            return
        visited.add(path)
        for name in re.findall(r'^lean_object\* ((?:(?:runtime|meta)_)?initialize_\w+)\(uint8_t builtin\);', texts[path], re.MULTILINE):
            if name in index:
                visit(index[name])
        if path in constants and constants[path]:
            ordered.append(hook(path))

    for path in sorted(selected):
        visit(path)
    text = '\n'.join('void ' + name + '(void);' for name in ordered)
    text += '\nvoid json_initialize_constants(void) {\n'
    text += '\n'.join(name + '();' for name in ordered) + '\n}\n'
    path = WORK / 'initialize.c'
    write_changed(path, text)
    return path


for attempt in range(80):
    sources = [module_source(path) for path in sorted(selected)] + [initialize_source()]
    objects = [str(path.relative_to(ROOT).with_suffix('.o')) for path in sources]
    write_changed(WORK / 'modules.mk', 'LEAN_OBJECTS := ' + ' '.join(objects) + '\n')
    map_file = WORK / 'link.map'
    result = make('link', capture=True)
    if result.returncode:
        missing = set(re.findall(r'undefined symbol: (\w+)', result.stderr))
        if not missing or any(symbol not in index or index[symbol] in selected for symbol in missing):
            raise SystemExit(result.stderr)
        additions = {index[symbol] for symbol in missing}
        print(f'Adding {len(additions)} Lean modules ({len(selected) + len(additions)} total)', flush=True)
        for path in sorted(additions):
            select(path)
        continue
    linked = map_file.read_text()
    added = 0
    for path in selected:
        for symbol in global_pattern.findall(texts[path]):
            if symbol not in constants[path] and re.search(r'\b' + re.escape(symbol) + r'\s*$', linked, re.MULTILINE):
                constants[path].add(symbol)
                added += 1
    if added:
        print(f'Initializing {added} additional retained constants', flush=True)
        continue
    (WORK / 'modules.txt').write_text('\n'.join(str(path.relative_to(ROOT)) for path in sorted(selected)) + '\n')
    (WORK / 'constants.txt').write_text('\n'.join(symbol for path in sorted(constants) for symbol in sorted(constants[path])) + '\n')
    break
else:
    raise SystemExit('Dependency/initialization closure did not converge')
